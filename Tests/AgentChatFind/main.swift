import Foundation

func check(_ condition: @autoclosure () -> Bool, _ message: String) {
    guard condition() else { fatalError(message) }
}

var index = AgentChatFindMatches()
index.search("a", ids: ["one", "two", "three"], texts: ["a a", "abc", "a"], start: (0, 1))
check(index.count == 4 && index.currentIndex == 1 && index.current?.range.location == 2, "start mid-row")
index.step(forward: true)
check(index.current?.rowId == "two" && index.current?.ordinal == 0, "row order")
index.step(forward: true)
index.step(forward: true)
check(index.currentIndex == 0, "forward wraps")
index.step(forward: false)
check(index.current?.rowId == "three", "backward wraps")
index.update(ids: ["one", "two", "three"], texts: ["a a", "abc", "a a"], from: 2)
check(index.count == 5 && index.current?.rowId == "three" && index.current?.ordinal == 0, "tail update preserves current")
index.update(ids: ["one", "two", "three"], texts: ["a a", "abc", "none"], from: 2)
check(index.count == 3 && index.currentIndex == 0, "lost tail match wraps")
index.step(forward: true)
index.step(forward: true)
index.update(ids: ["one", "three"], texts: ["a a", "a"], from: 1)
check(index.current?.rowId == "three", "removed current row selects its successor")
index.search("a", ids: ["one"], texts: ["a a"], start: (0, 99))
check(index.currentIndex == 0, "search wraps past last position")
index.search("cafe", ids: ["unicode"], texts: ["😀 CAFÉ cafe"], start: (0, 0))
check(index.count == 2 && index.current?.range == NSRange(location: 3, length: 4), "case, accents and UTF-16")
index.search("other", ids: ["unicode"], texts: ["other CAFÉ cafe"], start: (0, 0))
check(index.count == 1 && index.current?.range.length == 5, "query change replaces matches")
index.search("", ids: ["unicode"], texts: ["anything"], start: (0, 0))
index.step(forward: true)
check(index.count == 0 && index.current == nil && index.currentIndex == nil, "empty query")
index.update(ids: [], texts: [], from: 0)
check(index.current == nil, "empty transcript")

index.search("hit", ids: ["a", "b", "c"], texts: ["hit", "hit hit", "hit"], start: (1, 1))
check(index.current?.rowId == "b" && index.current?.ordinal == 1, "second match in row")
index.update(ids: ["a", "new", "b", "c"], texts: ["hit", "", "prefix hit hit", "hit"], from: 1)
check(index.current?.row == 2 && index.current?.ordinal == 1 && index.current?.range.location == 11,
      "moved current row keeps ordinal even when text shifts")
index.update(ids: ["a", "new", "b", "c"], texts: ["hit", "", "hit", "hit"], from: 2)
check(index.current?.rowId == "c", "lost ordinal selects next row after old position")
index.step(forward: false)
check(index.current?.rowId == "b", "backward steps within transcript")
index.search("hit", ids: ["a", "b"], texts: ["hit", "hit"], start: (0, 0))
index.update(ids: ["a", "b"], texts: ["hit", "hit hit"], from: 1)
check(index.currentIndex == 0 && index.count == 3, "unchanged current prefix is retained")
index.update(ids: ["a"], texts: ["hit"], from: 1)
check(index.currentIndex == 0 && index.count == 1, "removing suffix keeps prefix offsets valid")
print("Agent chat find tests passed")
